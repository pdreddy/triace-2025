import { test, expect } from './fixtures.js';

test('standings replay the winner climbing and the loser sliding, with real ranks, mobile layout and reduced motion', async ({ page, browser }) => {
  test.setTimeout(90000);
  await page.goto('/admin/login');
  await page.getByLabel('Username or email').fill('reddi2026');
  await page.getByLabel('Password', { exact: true }).fill('local-e2e-test-password');
  await page.getByRole('button', { name: 'Sign in ↗', exact: true }).click();
  await expect(page).toHaveURL(/\/home$/);
  expect((await page.request.post('/api/ladder-demo-seed', { data: {} })).ok()).toBeTruthy();
  const login = async (target, n) => expect((await target.request.post('/api/ladder-demo-login', { data: { playerId: `ladder_demo_${n}` } })).ok()).toBeTruthy();
  const act = async (target, payload) => {
    const response = await target.request.post('/api/ladder-action', { data: { seasonId: 'demo', ...payload } });
    expect(response.ok(), await response.text()).toBeTruthy(); return response.json();
  };
  await login(page, 14);
  const { challengeId } = await act(page, { action: 'challenge', opponentId: 'ladder_demo_13' });
  await login(page, 13);
  await act(page, { action: 'respond', challengeId, accept: true });
  await login(page, 14);
  await act(page, { action: 'submit', challengeId, winnerId: 'ladder_demo_14', score: '6-3 6-2' });
  await page.goto('/ladder');
  await expect(page.getByTestId('my-ladder-card')).toContainText('Demo Player 14');
  await expect(page.locator('.result-playing')).toHaveCount(0);
  const opponent = await browser.newContext({ baseURL: new URL(page.url()).origin });
  const spectator = await browser.newContext({ baseURL: new URL(page.url()).origin });
  const spectatorPage = await spectator.newPage();
  await spectatorPage.goto('/ladder');
  await expect(spectatorPage.getByRole('list', { name: 'Ladder standings' })).toBeVisible();
  try {
    const otherPage = await opponent.newPage();
    await login(otherPage, 13);
    await act(otherPage, { action: 'confirm', challengeId });
    const result = page.getByRole('dialog', { name: 'Up you go!' });
    await expect(result).toBeVisible();
    await expect(spectatorPage.locator('[data-player-id="ladder_demo_14"]')).toHaveClass(/result-playing/);
    await expect(spectatorPage.getByRole('dialog')).toHaveCount(0);
    await result.getByRole('button', { name: 'Back to the ladder' }).click();
    const banner = page.getByRole('region', { name: 'Latest ladder result' });
    await expect(banner).toContainText('Demo Player 14 beat Demo Player 13');
    const winner = page.locator('.ladder-list [data-player-id="ladder_demo_14"]');
    const loser = page.locator('.ladder-list [data-player-id="ladder_demo_13"]');
    await expect(winner).toHaveClass(/result-winner/);
    await expect(loser).toHaveClass(/result-loser/);
    await expect(winner.getByLabel('Position 13', { exact: true })).toHaveText('13');
    await expect(loser.getByLabel('Position 14', { exact: true })).toHaveText('14');
    await expect(winner.locator('.table-result-tag')).toContainText('WIN');
    await expect(winner.locator('.table-result-tag')).toContainText('#14 → #13');
    await expect(loser.locator('.rank-trail.down')).toBeVisible();
    const replay = banner.getByRole('button', { name: 'Replay on table' });
    await expect(replay).toBeEnabled({ timeout: 7000 });
    await replay.click();
    await expect(winner).toHaveClass(/rank-reordering/);
    expect(await winner.evaluate(node => node.getAnimations().some(a => a.playState === 'running' && a.effect.getKeyframes().some(frame => String(frame.transform).includes('translateY'))))).toBeTruthy();
    await expect(winner).toBeInViewport({ ratio: 1 });
    await page.screenshot({ path: 'work/table-result-desktop.png' });
    await expect(replay).toBeEnabled({ timeout: 7000 });
    await page.setViewportSize({ width: 320, height: 740 });
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await replay.click();
    await expect(winner).toHaveCSS('animation-name', 'none');
    await expect(loser.locator('.rank-slider')).toHaveCSS('animation-name', 'none');
    expect(await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)).toBeLessThanOrEqual(0);
    const nameBox = await winner.locator('.lwho').boundingBox(), pointsBox = await winner.locator('.lnums').first().boundingBox();
    expect(nameBox.y + nameBox.height).toBeLessThanOrEqual(pointsBox.y + 1);
    await expect(winner).toBeInViewport({ ratio: 1 });
    await page.screenshot({ path: 'work/table-result-mobile.png' });
    await page.reload();
    await expect(page.getByRole('heading', { name: 'Standings', exact: true })).toBeVisible();
    await expect(page.getByRole('dialog')).toHaveCount(0);
    await expect(page.locator('.result-playing')).toHaveCount(0);
  } finally { await opponent.close(); await spectator.close(); }
});
